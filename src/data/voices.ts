/**
 * Helper to get matching voice by use-case and gender
 */
export function getVoiceForUseCaseAndGender(useCase: VoiceUseCase, gender: VoiceGender): Voice {
  const match = VOICES_CATALOG.find((v) => v.useCase === useCase && v.gender === gender);
  if (match) return match;
  const fallback = VOICES_CATALOG.find((v) => v.gender === gender);
  return fallback || VOICES_CATALOG[0];
}
